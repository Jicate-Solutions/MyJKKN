        )
    );

-- ---------------------------------------------------------------------------
-- 6. Smoke test — verify all 3 tables exist + key columns + constraints
-- ---------------------------------------------------------------------------
-- SELECT-only verification (no INSERT) per locked rule against NOT-NULL-column
-- omission breaking smoke INSERTs.
DO $$
DECLARE
    v_table_count INT;
    v_outcome_check_present BOOLEAN;
BEGIN
    SELECT COUNT(*) INTO v_table_count
    FROM information_schema.tables
    WHERE table_schema = 'public'
      AND table_name IN (
          'hr_disciplinary_cases',
          'hr_disciplinary_events',
          'hr_disciplinary_witnesses'
      );

    IF v_table_count <> 3 THEN
        RAISE EXCEPTION 'T6.2 smoke FAILED: expected 3 disciplinary tables, found %', v_table_count;
    END IF;

    -- Verify outcome enum check exists
    SELECT EXISTS (
        SELECT 1 FROM information_schema.check_constraints
        WHERE constraint_schema = 'public'
          AND constraint_name = 'chk_disc_case_outcome'
    ) INTO v_outcome_check_present;

    IF NOT v_outcome_check_present THEN
        RAISE EXCEPTION 'T6.2 smoke FAILED: chk_disc_case_outcome constraint not found';
    END IF;

    RAISE NOTICE 'T6.2 smoke OK — 3 tables + RLS + outcome constraint verified.';
END $$;

COMMIT;
